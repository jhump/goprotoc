package goprotoc

import (
	"bytes"
	"io"
	"os"
	"path/filepath"
	"testing"
)

// TestGoToolPluginIntegration runs goprotoc against the module in
// testdata/gotool, which declares a protoc plugin as a tool in its go.mod. It
// covers both ways of reaching such a plugin: discovery from the go.mod tool
// directives, and an explicit --plugin=gotool: flag.
func TestGoToolPluginIntegration(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping test that invokes the go command")
	}

	modDir, err := filepath.Abs(filepath.Join("testdata", "gotool"))
	if err != nil {
		t.Fatalf("failed to resolve testdata module: %v", err)
	}
	// The go.mod that declares the plugin is found relative to the working
	// directory, the same way the go command finds it.
	chdir(t, modDir)

	// Tool directives require Go 1.24 or later. Probe for support directly
	// rather than parsing the toolchain's version.
	var resolver goToolResolver
	tools, err := resolver.toolDirectives()
	if err != nil {
		t.Skipf("go toolchain cannot read tool directives, skipping: %v", err)
	}
	if _, ok := tools.plugins["testplugin"]; !ok {
		t.Skipf("go toolchain did not report the testplugin tool directive, skipping")
	}

	testCases := []struct {
		name string
		args []string
	}{
		{
			name: "discovered from go.mod",
			args: []string{"test.proto"},
		},
		{
			name: "explicit gotool plugin",
			args: []string{"--plugin=gotool:example.com/gotooltest/protoc-gen-testplugin", "test.proto"},
		},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			outDir := t.TempDir()
			args := append([]string{"goprotoc", "--testplugin_out=" + outDir}, testCase.args...)
			var stderr bytes.Buffer
			if code := Run(args, nil, io.Discard, &stderr); code != 0 {
				t.Fatalf("goprotoc exited with code %d: %s", code, stderr.String())
			}

			contents, err := os.ReadFile(filepath.Join(outDir, "testplugin-output.txt"))
			if err != nil {
				t.Fatalf("plugin did not produce the expected output: %v", err)
			}
			if expected := "generated by protoc-gen-testplugin"; string(contents) != expected {
				t.Errorf("expected output %q, got %q", expected, string(contents))
			}
		})
	}
}

// chdir changes to the given directory for the duration of the test. It is
// testing.T.Chdir, which this module's Go version predates.
func chdir(t *testing.T, dir string) {
	t.Helper()
	wd, err := os.Getwd()
	if err != nil {
		t.Fatalf("failed to get working directory: %v", err)
	}
	if err := os.Chdir(dir); err != nil {
		t.Fatalf("failed to change to %s: %v", dir, err)
	}
	t.Cleanup(func() {
		if err := os.Chdir(wd); err != nil {
			t.Fatalf("failed to restore working directory: %v", err)
		}
	})
}
